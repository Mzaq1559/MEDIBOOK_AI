/**
 * Translate a raw backend date string into a locale-aware display.
 * Numbers/dates stay LTR inside RTL via dir="ltr" wrapper.
 */
export function translateDate(isoString: string, lang: Lang, opts?: { weekday?: 'long' | 'short'; month?: 'long' | 'short'; day?: 'numeric'; year?: 'numeric' }): string {
  try {
    const d = new Date(isoString);
    if (isNaN(d.getTime())) return isoString;
    const weekday = opts?.weekday ?? 'short';
    const month = opts?.month ?? 'short';
    const day = opts?.day ?? 'numeric';
    const year = opts?.year;

    if (lang === 'en') {
      return d.toLocaleDateString('en-US', { weekday, month, day, ...(year ? { year } : {}) } as Intl.DateTimeFormatOptions);
    }

    // Urdu
    const enParts = d.toLocaleDateString('en-US', { weekday, month, day, ...(year ? { year } : {}) } as Intl.DateTimeFormatOptions);
    let result = enParts;
    // Replace day names
    for (const [enKey, urVal] of Object.entries(weekday === 'long' ? urduDays : urduDaysShort)) {
      result = result.replace(enKey, urVal);
    }
    // Replace month names
    for (const [enKey, urVal] of Object.entries(month === 'long' ? urduMonths : urduMonthsShort)) {
      result = result.replace(enKey, urVal);
    }
    return result;
  } catch {
    return isoString;
  }
}

/** Translate a time string to locale display */
export function translateTime(isoString: string, lang: Lang): string {
  try {
    const d = new Date(isoString);
    if (isNaN(d.getTime())) return isoString;
    return d.toLocaleTimeString(lang === 'en' ? 'en-US' : 'ur-PK', { hour: '2-digit', minute: '2-digit' });
  } catch {
    return isoString;
  }
}

/** Translate an urgency level from backend to display label */
export function translateUrgency(level: string | undefined | null, lang: Lang): string {
  if (!level) return lang === 'en' ? 'Not assessed' : 'جائزہ نہیں لیا گیا';
  const key = level.toLowerCase();
  return urgencyMap[key]?.[lang] ?? (lang === 'en' ? 'Not assessed' : 'جائزہ نہیں لیا گیا');
}

/** Translate a status from backend to display label */
export function translateStatus(status: string, lang: Lang): string {
  const key = status.toLowerCase();
  return statusMap[key]?.[lang] ?? status;
}

/** Translate a triage reason code to display text */
export function translateReason(reason: string | undefined | null, lang: Lang): string | null {
  if (!reason) return null;
  return reasonDisplayMap[reason]?.[lang] ?? reason.replace(/_/g, ' ');
}
